Console.BackgroundColor = ConsoleColor.White;

//Comando Repetição For Crescente
for (int i = 0; i <= 67; i++)
{
    Console.ForegroundColor = ConsoleColor.Black;
    Console.WriteLine(i);
}

//Comando Repetição For Decrescente
for (int i = 67; i >= 1; i--)
{
    Console.ForegroundColor= ConsoleColor.DarkMagenta;
    Console.WriteLine(i);
}